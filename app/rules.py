"""Posting-rules engine. Pure functions: destination rules + content + recent posts -> decision.

Checked before every post (orchestrator) and inside every connector's validate() (contract path):
  frequency cap      -> RESCHEDULE with not_before (needs the publication ledger, so orchestrator only)
  self-promotion     -> BLOCK when the destination bans it and the content is, or might be, promotional
  link policy        -> BLOCK when links are banned, too many, from a disallowed domain or a URL shortener
  AI disclosure      -> auto-append a disclosure in the destination's language (orchestrator), or BLOCK (validate)
  language           -> BLOCK when the content language differs from the community's
When the promotion check is unsure, it blocks: one careless post can get the account banned.
"""
import re
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from urllib.parse import urlparse

URL_RE = re.compile(r"https?://[^\s)>\]\"']+", re.IGNORECASE)
SHORTENERS = {"bit.ly", "t.co", "tinyurl.com", "goo.gl", "ow.ly", "buff.ly", "rebrand.ly", "is.gd", "cutt.ly", "lnkd.in"}
PROMO_PHRASES = [
    "buy now", "sign up", "signup", "subscribe", "free trial", "discount", "promo code", "coupon", "use code",
    "limited time", "limited offer", "get started today", "download now", "join now", "book a demo",
    "check out our", "try our", "our product", "our app", "our tool", "our platform", "early access",
    "join our waitlist", "upgrade to", "special offer", "sale ends", "act now",
]
DISCOUNT_RE = re.compile(r"\d+\s?%\s?off|\$\s?\d+(\.\d\d)?|€\s?\d+|₹\s?\d+", re.IGNORECASE)
PROMO_BLOCK_THRESHOLD = 0.3  # score >= this is treated as promotional ("when unsure, block")

DISCLOSURES = {
    "en": "Disclosure: this post was created with the help of AI.",
    "de": "Hinweis: Dieser Beitrag wurde mit Hilfe von KI erstellt.",
    "fr": "Avertissement : ce message a été créé avec l'aide de l'IA.",
    "es": "Aviso: esta publicación se creó con ayuda de IA.",
    "pt": "Aviso: esta publicação foi criada com a ajuda de IA.",
    "it": "Nota: questo post è stato creato con l'aiuto dell'IA.",
    "nl": "Let op: dit bericht is gemaakt met behulp van AI.",
    "hi": "सूचना: यह पोस्ट एआई की मदद से बनाई गई है।",
    "ja": "注記：この投稿はAIの支援を受けて作成されました。",
}
DISCLOSURE_MARKERS = ["ai-generated", "ai generated", "generated by ai", "created with ai", "with the help of ai",
                      "#aigenerated", "#ai_generated", "made with ai", "ai-assisted", "ai assisted"]


@dataclass
class Check:
    rule: str
    passed: bool
    detail: str
    code: str | None = None

    def as_dict(self) -> dict:
        return {"rule": self.rule, "passed": self.passed, "detail": self.detail, "code": self.code}


@dataclass
class Decision:
    action: str  # allow | block | reschedule
    checks: list[Check]
    rendition: dict
    warnings: list[str] = field(default_factory=list)
    not_before: datetime | None = None

    @property
    def failed(self) -> list[Check]:
        """Failed checks, blocking ones first: rescheduling cannot fix a block, so its reason leads."""
        failed = [c for c in self.checks if not c.passed]
        return sorted(failed, key=lambda c: c.code == "DEST_RULE_FREQUENCY_CAP")

    @property
    def code(self) -> str | None:
        return self.failed[0].code if self.failed else None

    @property
    def reason(self) -> str:
        return "; ".join(c.detail for c in self.failed)


def primary_lang(tag: str | None) -> str:
    return (tag or "").split("-")[0].split("_")[0].lower()


def _domain(url: str) -> str:
    host = (urlparse(url).hostname or "").lower()
    return host[4:] if host.startswith("www.") else host


def _domain_matches(domain: str, allowed: list[str]) -> bool:
    return any(domain == a or domain.endswith("." + a) for a in (x.lower().lstrip(".") for x in allowed))


def links_in(rendition: dict) -> list[str]:
    links = URL_RE.findall(rendition.get("body") or "")
    if rendition.get("link_url"):
        links.append(rendition["link_url"])
    return links


def promo_score(rendition: dict, own_domains: list[str]) -> tuple[float, list[str]]:
    """0..1 likelihood the content is self-promotion, with the signals that raised it."""
    if rendition.get("is_promotional") is True:
        return 1.0, ["marked promotional by the creator"]
    text = f"{rendition.get('title', '')}\n{rendition.get('body', '')}".lower()
    signals, score = [], 0.0
    phrases = [p for p in PROMO_PHRASES if re.search(rf"\b{re.escape(p)}\b", text)]
    if phrases:
        score += min(0.6, 0.3 * len(phrases))
        signals.append(f"promotional phrases: {', '.join(phrases[:5])}")
    if DISCOUNT_RE.search(text):
        score += 0.4
        signals.append("price or discount mentioned")
    own = [u for u in links_in(rendition) if own_domains and _domain_matches(_domain(u), own_domains)]
    if own:
        score += 0.5
        signals.append(f"links to own site: {_domain(own[0])}")
    return min(1.0, score), signals


def has_disclosure(text: str) -> bool:
    low = text.lower()
    return any(m in low for m in DISCLOSURE_MARKERS) or any(d.lower() in low for d in DISCLOSURES.values())


def stateless_checks(rendition: dict, rules: dict, own_domains: list[str] | None = None,
                     autofix: bool = False) -> tuple[list[Check], dict, list[str]]:
    """Checks that need no history. Returns (checks, possibly-modified rendition, warnings)."""
    own_domains = own_domains or []
    r = dict(rendition)
    checks: list[Check] = []
    warnings: list[str] = []

    # self-promotion
    if rules.get("self_promo_allowed") is False:
        score, signals = promo_score(r, own_domains)
        if score >= PROMO_BLOCK_THRESHOLD:
            checks.append(Check("self_promotion", False,
                                f"Destination bans self-promotion and the content looks promotional "
                                f"(score {score:.2f}: {'; '.join(signals)})", "DEST_RULE_SELF_PROMO"))
        else:
            checks.append(Check("self_promotion", True, f"No promotion detected (score {score:.2f})"))
    else:
        checks.append(Check("self_promotion", True, "Destination allows self-promotion"))

    # link policy
    policy = rules.get("link_policy") or {}
    links = links_in(r)
    problems = []
    if policy.get("allowed") is False and links:
        problems.append(f"links are not allowed ({len(links)} found)")
    if policy.get("max_links") is not None and len(links) > policy["max_links"]:
        problems.append(f"{len(links)} links; maximum is {policy['max_links']}")
    if policy.get("allowed_domains"):
        bad = [u for u in links if not _domain_matches(_domain(u), policy["allowed_domains"])]
        if bad:
            problems.append(f"domain not allowed: {_domain(bad[0])}")
    blocked = [u for u in links if _domain_matches(_domain(u), policy.get("blocked_domains") or [])]
    if blocked:
        problems.append(f"blocked domain: {_domain(blocked[0])}")
    if policy.get("no_shorteners", True):
        short = [u for u in links if _domain(u) in SHORTENERS]
        if short:
            problems.append(f"URL shortener not allowed: {_domain(short[0])}")
    checks.append(Check("link_policy", not problems,
                        "; ".join(problems) if problems else f"{len(links)} link(s) within policy",
                        "DEST_RULE_LINK_POLICY" if problems else None))

    # AI-content disclosure
    if rules.get("disclosure_required") and r.get("ai_generated"):
        if has_disclosure(f"{r.get('title', '')}\n{r.get('body', '')}") or r.get("ai_disclosure"):
            checks.append(Check("ai_disclosure", True, "AI disclosure present"))
        elif autofix:
            lang = primary_lang(rules.get("language") or r.get("language")) or "en"
            text = DISCLOSURES.get(lang, DISCLOSURES["en"])
            r["body"] = f"{(r.get('body') or '').rstrip()}\n\n{text}"
            r["ai_disclosure"] = text
            warnings.append(f"AI_DISCLOSURE_ADDED: destination requires disclosure; appended ({lang})")
            checks.append(Check("ai_disclosure", True, f"Disclosure appended in '{lang}'"))
        else:
            checks.append(Check("ai_disclosure", False, "Destination requires AI-content disclosure; none found",
                                "DEST_RULE_DISCLOSURE_REQUIRED"))
    else:
        checks.append(Check("ai_disclosure", True, "Disclosure not required for this content"))

    # language
    dest_lang, content_lang = primary_lang(rules.get("language")), primary_lang(r.get("language"))
    if dest_lang and content_lang and dest_lang != content_lang:
        checks.append(Check("language", False, f"Community language is '{dest_lang}' but the content is "
                                               f"'{content_lang}'; a '{dest_lang}' rendition is needed",
                            "DEST_RULE_LANGUAGE_MISMATCH"))
    else:
        checks.append(Check("language", True, f"Language matches ({dest_lang or 'unspecified'})"))
    return checks, r, warnings


def cap_window(cap: dict) -> timedelta:
    return timedelta(days=cap.get("per_days", 0), hours=cap.get("per_hours", 0)) or timedelta(days=1)


def frequency_check(cap: dict | None, recent: list[datetime], now: datetime) -> tuple[Check, datetime | None]:
    if not cap or not cap.get("posts"):
        return Check("frequency_cap", True, "No frequency cap"), None
    window = cap_window(cap)
    in_window = sorted(t for t in recent if now - t < window)
    limit = int(cap["posts"])
    if len(in_window) < limit:
        return Check("frequency_cap", True, f"{len(in_window)}/{limit} posts in the last {window}"), None
    not_before = in_window[-limit] + window
    return Check("frequency_cap", False,
                 f"Cap of {limit} post(s) per {window} reached; next slot {not_before.isoformat()}",
                 "DEST_RULE_FREQUENCY_CAP"), not_before


def evaluate(rendition: dict, rules: dict, recent: list[datetime], now: datetime,
             own_domains: list[str] | None = None, is_test: bool = False) -> Decision:
    """Full decision for the orchestrator. Test posts (certification) are exempt from the cap only."""
    if rules.get("automation_allowed") is False:
        return Decision("block", [Check("automation", False, "Automated posting is not allowed here; "
                                        "a person must post (use an assist pack)",
                                        "DEST_RULE_AUTOMATION_NOT_ALLOWED")], dict(rendition))
    checks, r, warnings = stateless_checks(rendition, rules, own_domains, autofix=True)
    if is_test:
        cap_check, not_before = Check("frequency_cap", True, "Certification test post: cap not applied"), None
    else:
        cap_check, not_before = frequency_check(rules.get("frequency_cap"), recent, now)
    checks.insert(0, cap_check)
    blocking = [c for c in checks if not c.passed and c.code != "DEST_RULE_FREQUENCY_CAP"]
    if blocking:
        return Decision("block", checks, r, warnings)
    if not_before:
        return Decision("reschedule", checks, r, warnings, not_before)
    return Decision("allow", checks, r, warnings)


RULE_FIELDS = ("self_promo_allowed", "link_policy", "disclosure_required", "automation_allowed", "frequency_cap",
               "language")


def rules_of(destination) -> dict:
    """Rule fields from a Destination row or DestinationRef."""
    return {f: getattr(destination, f, None) for f in RULE_FIELDS}
